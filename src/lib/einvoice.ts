/**
 * GST e-Invoice (IRP / NIC) bulk-upload JSON.
 *
 * Ported from the e-Invoice module of the Sheetaldies ERP
 * (akashshinde700/sheetaldies_erp, backend/src/controllers/einvoice.controller.js).
 *
 * ManuFlow has no direct IRP/GSP connection. The flow is file-based, exactly like
 * every small ERP does it:
 *
 *   1. `buildEInvoiceJson()` produces the NIC "Invoice Bulk Upload" schema (v1.1)
 *      for one invoice — the portal takes an ARRAY, so a single invoice is still
 *      wrapped in one.
 *   2. The user uploads that file at https://einvoice1.gst.gov.in/Invoice/BulkUpload,
 *      generates the IRN + e-Way Bill there, and downloads the result sheet.
 *   3. The IRN / Ack / e-Way Bill numbers come back onto the invoice (ManuFlow lets
 *      them be set from the invoice screen, or generated by the mock gateway).
 *
 * `validateForIrp()` runs before the download so the portal's error report is not
 * the first place a missing GSTIN or PIN shows up.
 */

export interface IrpParty {
  name?: string | null
  gstin?: string | null
  addressLine?: string | null
  addressLine2?: string | null
  city?: string | null
  state?: string | null
  stateCode?: string | null
  pincode?: string | null
  phone?: string | null
  email?: string | null
}

export interface IrpItem {
  description?: string | null
  itemName?: string | null
  hsn?: string | null
  uom?: string | null
  qty?: number | null
  rate?: number | null
  lineTotal?: number | null
  amount?: number | null
  gstRate?: number | null
  cessRate?: number | null
  cess?: number | null
}

export interface IrpInvoice {
  number: string
  date: Date | string
  customer?: IrpParty | null
  items?: IrpItem[] | null
  subtotal: number
  cgst: number
  sgst: number
  igst: number
  cess?: number | null
  grandTotal: number
  roundOff?: number | null
  freightCharge?: number | null
  freightGstRate?: number | null
  packingCharge?: number | null
  packingGstRate?: number | null
  placeOfSupply?: string | null
  isInterState?: boolean | null
  docType?: string | null
  reverseCharge?: boolean | null
}

/** SAC used for the freight / packing service lines. */
export const FREIGHT_SAC = '996511'
export const PACKING_SAC = '998540'

export interface NicItem {
  SlNo: string; PrdDesc: string; IsServc: 'Y' | 'N'; HsnCd: string; Qty: number; Unit: string; UnitPrice: number
  TotAmt: number; Discount: number; AssAmt: number; GstRt: number; CgstAmt: number; SgstAmt: number; IgstAmt: number
  CesAmt?: number; CesRt?: number; TotItemVal: number
}

/** NIC allows at most 16 characters in the document number. */
export const NIC_DOC_NO_MAX = 16
const GSTIN_RE = /^\d{2}[A-Z]{5}\d{4}[A-Z][1-9A-Z]Z[0-9A-Z]$/
const round2 = (n: number) => Math.round((Number.isFinite(n) ? n : 0) * 100) / 100

/** DD/MM/YYYY — the only date format the portal accepts. */
export function nicDate(value: Date | string | null | undefined): string | null {
  if (!value) return null
  const d = value instanceof Date ? value : new Date(value)
  if (Number.isNaN(d.getTime())) return null
  return `${String(d.getUTCDate()).padStart(2, '0')}/${String(d.getUTCMonth() + 1).padStart(2, '0')}/${d.getUTCFullYear()}`
}

/** The first two digits of a GSTIN are the state code — that is also the place of supply. */
export function partyStateCode(party?: IrpParty | null): string {
  const fromGstin = String(party?.gstin || '').trim().slice(0, 2)
  if (/^\d{2}$/.test(fromGstin)) return fromGstin
  const explicit = String(party?.stateCode || '').trim()
  if (/^\d{1,2}$/.test(explicit)) return explicit.padStart(2, '0')
  return ''
}

/** 6-digit PIN: the pincode field, else the last 6-digit run in the address. */
export function partyPin(party?: IrpParty | null): number | null {
  let digits = String(party?.pincode || '').replace(/\D/g, '')
  if (digits.length !== 6) {
    const found = `${party?.addressLine || ''} ${party?.addressLine2 || ''}`.match(/(?<!\d)\d{6}(?!\d)/g)
    if (found && found.length) digits = found[found.length - 1]
  }
  return digits.length === 6 ? Number(digits) : null
}

/** NIC rejects an address longer than 100 characters. */
const addr = (party?: IrpParty | null, second?: boolean) => {
  const parts = second ? [party?.addressLine2] : [party?.addressLine]
  return String(parts.filter(Boolean).join(' ')).replace(/\s+/g, ' ').trim().slice(0, 100)
}

/**
 * Everything the portal would reject, found before the download.
 * @returns a list of human-readable problems — empty means ready.
 */
export function validateForIrp(invoice: IrpInvoice, seller?: IrpParty | null): string[] {
  const problems: string[] = []
  const buyer = invoice.customer
  const docNo = String(invoice.number || '')

  if (invoice.docType === 'PROFORMA') problems.push('A proforma invoice cannot be reported to the IRP — raise the tax invoice first.')
  if (invoice.docType === 'BILL_OF_SUPPLY') problems.push('A bill of supply is not reportable as a tax invoice (e-invoicing applies to taxable B2B supplies).')
  if (!docNo) problems.push('Invoice has no number.')
  else {
    if (docNo.length > NIC_DOC_NO_MAX) problems.push(`Invoice number "${docNo}" is ${docNo.length} characters — NIC allows only ${NIC_DOC_NO_MAX}.`)
    if (/^[0/-]/.test(docNo)) problems.push(`Invoice number "${docNo}" cannot start with 0, / or -.`)
  }
  if (!nicDate(invoice.date)) problems.push('Invoice date is missing or invalid.')

  if (!GSTIN_RE.test(String(seller?.gstin || '').trim())) {
    problems.push(`Seller (${seller?.name || 'your company'}) has an invalid GSTIN — set it in Settings → Company Profile.`)
  }
  if (!GSTIN_RE.test(String(buyer?.gstin || '').trim())) {
    problems.push(`Buyer (${buyer?.name || 'unknown'}) has an invalid GSTIN — e-invoicing is for B2B supplies only.`)
  }
  if (!partyPin(seller)) problems.push('Seller is missing a 6-digit PIN code.')
  if (!partyPin(buyer)) problems.push('Buyer is missing a 6-digit PIN code.')
  if (!partyStateCode(seller)) problems.push("Could not determine the seller's state code.")
  if (!partyStateCode(buyer)) problems.push("Could not determine the buyer's state code.")

  const items = invoice.items || []
  if (!items.length) problems.push('Invoice has no items.')
  items.forEach((it, i) => {
    const hsn = String(it.hsn || '').trim()
    if (!/^\d{4,8}$/.test(hsn)) problems.push(`Item ${i + 1} ("${it.itemName || it.description || 'line'}") is missing a valid HSN/SAC code.`)
    if (!(Number(it.qty) > 0)) problems.push(`Item ${i + 1} has no quantity.`)
  })
  if (!invoice.isInterState && round2(invoice.igst) > 0) problems.push('Intra-state invoice carries IGST — check the place of supply.')

  return problems
}

export interface NicInvoice {
  Version: string
  TranDtls: { TaxSch: string; SupTyp: string; RegRev: string; IgstOnIntra: string }
  DocDtls: { Typ: string; No: string; Dt: string | null }
  SellerDtls: Record<string, unknown>
  BuyerDtls: Record<string, unknown>
  ItemList: NicItem[]
  ValDtls: Record<string, number>
}

/**
 * NIC "Invoice Bulk Upload" schema v1.1 for one invoice.
 * Lines carry their own discount and tax (freight / packing become service lines), so Σ item values
 * equal the header: AssVal + taxes + round-off === TotInvVal, which is what the portal validates.
 */
export function buildEInvoiceJson(invoice: IrpInvoice, seller?: IrpParty | null): NicInvoice[] {
  const buyer = invoice.customer
  const interState = !!invoice.isInterState || round2(invoice.igst) > 0

  // Line values follow computeBillTotals (src/lib/erp-helpers.ts) to the paisa, so Σ item values ==
  // the header totals the portal checks: tax on the stored taxable value, an odd paisa to CGST.
  const lineTax = (assAmt: number, gstRt: number) => {
    const taxC = Math.round((Math.round(assAmt * 100) * gstRt) / 100)
    if (interState) return { cgstAmt: 0, sgstAmt: 0, igstAmt: taxC / 100 }
    const half = Math.round(taxC / 2)
    return { cgstAmt: half / 100, sgstAmt: (taxC - half) / 100, igstAmt: 0 }
  }

  const itemList: NicItem[] = (invoice.items || []).map((it, i) => {
    const hsn = String(it.hsn || '').trim()
    const isService = hsn.startsWith('99')
    const qty = Number(it.qty) || 0
    const rate = Number(it.rate) || 0
    const gross = round2(qty * rate)
    // the stored line value is already net of the line discount and its share of the bill discount
    const assAmt = round2(Number(it.amount) || Number(it.lineTotal) || gross)
    const discount = round2(Math.max(0, gross - assAmt))
    const gstRt = Number(it.gstRate) || 0
    const cessRt = Number(it.cessRate ?? it.cess) || 0
    const { cgstAmt, sgstAmt, igstAmt } = lineTax(assAmt, gstRt)
    const cesAmt = cessRt ? Math.round(Math.round(assAmt * 100) * cessRt / 100) / 100 : 0
    return {
      SlNo: String(i + 1),
      PrdDesc: String(it.itemName || it.description || 'Item').slice(0, 300),
      IsServc: isService ? 'Y' : 'N',
      HsnCd: hsn,
      Qty: Number(qty.toFixed(3)),
      Unit: String(it.uom || 'NOS').toUpperCase().slice(0, 8),
      UnitPrice: Number(rate.toFixed(3)),
      TotAmt: Math.max(gross, assAmt),
      Discount: discount,
      AssAmt: assAmt,
      GstRt: gstRt,
      CgstAmt: cgstAmt,
      SgstAmt: sgstAmt,
      IgstAmt: igstAmt,
      ...(cesAmt ? { CesAmt: cesAmt, CesRt: cessRt } : {}),
      TotItemVal: round2(assAmt + cgstAmt + sgstAmt + igstAmt + cesAmt),
    }
  })

  // Freight and packing carry GST, so the portal needs them as taxable service lines — as "other
  // charges" (non-taxable) their tax would not add up to the header tax heads.
  const charges: [string, string, number, number][] = [
    ['Freight charges', FREIGHT_SAC, Number(invoice.freightCharge) || 0, invoice.freightGstRate ?? 18],
    ['Packing charges', PACKING_SAC, Number(invoice.packingCharge) || 0, invoice.packingGstRate ?? 18],
  ]
  for (const [desc, sac, amount, rateRaw] of charges) {
    const amt = round2(amount)
    if (!(amt > 0)) continue
    const gstRt = Number(rateRaw) || 0
    const { cgstAmt, sgstAmt, igstAmt } = lineTax(amt, gstRt)
    itemList.push({
      SlNo: String(itemList.length + 1), PrdDesc: desc, IsServc: 'Y', HsnCd: sac, Qty: 1, Unit: 'OTH', UnitPrice: amt,
      TotAmt: amt, Discount: 0, AssAmt: amt, GstRt: gstRt, CgstAmt: cgstAmt, SgstAmt: sgstAmt, IgstAmt: igstAmt,
      TotItemVal: round2(amt + cgstAmt + sgstAmt + igstAmt),
    })
  }
  const assVal = round2(itemList.reduce((s, l) => s + l.AssAmt, 0))

  const sellerDtls = {
    Gstin: String(seller?.gstin || '').trim(),
    LglNm: String(seller?.name || '').slice(0, 100),
    Addr1: addr(seller),
    ...(addr(seller, true) ? { Addr2: addr(seller, true) } : {}),
    Loc: String(seller?.city || 'NA').slice(0, 50),
    Pin: partyPin(seller) ?? 0,
    Stcd: partyStateCode(seller),
    ...(seller?.phone ? { Ph: String(seller.phone).replace(/\D/g, '').slice(-12) } : {}),
    ...(seller?.email ? { Em: String(seller.email).slice(0, 100) } : {}),
  }
  const buyerDtls = {
    Gstin: String(buyer?.gstin || '').trim(),
    LglNm: String(buyer?.name || '').slice(0, 100),
    Pos: partyStateCode(buyer),
    Addr1: addr(buyer),
    ...(addr(buyer, true) ? { Addr2: addr(buyer, true) } : {}),
    Loc: String(buyer?.city || 'NA').slice(0, 50),
    Pin: partyPin(buyer) ?? 0,
    Stcd: partyStateCode(buyer),
    ...(buyer?.phone ? { Ph: String(buyer.phone).replace(/\D/g, '').slice(-12) } : {}),
    ...(buyer?.email ? { Em: String(buyer.email).slice(0, 100) } : {}),
  }

  return [{
    Version: '1.1',
    TranDtls: {
      TaxSch: 'GST',
      SupTyp: 'B2B',
      RegRev: invoice.reverseCharge ? 'Y' : 'N',
      IgstOnIntra: 'N',
    },
    DocDtls: { Typ: 'INV', No: String(invoice.number || ''), Dt: nicDate(invoice.date) },
    SellerDtls: sellerDtls,
    BuyerDtls: buyerDtls,
    ItemList: itemList,
    ValDtls: {
      AssVal: assVal,
      CgstVal: round2(invoice.cgst || 0),
      SgstVal: round2(invoice.sgst || 0),
      IgstVal: round2(invoice.igst || 0),
      ...(round2(invoice.cess || 0) ? { CesVal: round2(invoice.cess || 0) } : {}),
      OthChrg: 0,
      RndOffAmt: round2(invoice.roundOff || 0),
      TotInvVal: round2(invoice.grandTotal),
    },
  }]
}

/** Portal the downloaded JSON is taken to. */
export const IRP_BULK_UPLOAD_URL = 'https://einvoice1.gst.gov.in/Invoice/BulkUpload'

export function einvoiceFileName(number: string): string {
  return `${String(number || 'invoice').replace(/[\\/:*?"<>|]+/g, '-')}_einvoice.json`
}
